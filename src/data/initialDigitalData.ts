/**
 * Auto-detect provider from phone prefix
 */
export function detectProviderFromPhone(phone: string): DigitalProviderInfo | undefined {
  const clean = phone.replace(/\D/g, '');
  if (clean.length < 4) return undefined;

  for (const provider of DIGITAL_PROVIDERS) {
    if (provider.prefixes) {
      for (const prefix of provider.prefixes) {
        if (clean.startsWith(prefix)) {
          return provider;
        }
      }
    }
  }
  return undefined;
}

/**
 * Generate simulated PLN Meter / Postpaid inquiry data
 */
export function sampleInquiryPLN(targetNumber: string): DigitalInquiryData {
  const clean = targetNumber.replace(/\D/g, '');
  const sampleNames = [
    'BAPAK HENDRA KURNIAWAN',
    'IBU SITI NURHALIZA',
    'RATNA KUSUMA DEWI',
    'AGUS SETIAWAN',
    'BUDI PRASETYO',
    'WARUNG IBU ENI',
    'TOKO SUMBER BERKAH',
  ];
  const powers = ['R1 / 450 VA', 'R1 / 900 VA', 'R1M / 900 VA', 'R1 / 1300 VA', 'R1 / 2200 VA', 'B1 / 3500 VA'];
  
  // Pick deterministic name & power based on last digits
  const sumDigits = clean.split('').reduce((acc, c) => acc + (parseInt(c, 10) || 0), 0);
  const name = sampleNames[sumDigits % sampleNames.length];
  const power = powers[sumDigits % powers.length];
  const kwh = (18.5 + (sumDigits % 35)).toFixed(1) + ' kWh';

  return {
    subscriberName: name,
    subscriberId: clean,
    meterNo: clean,
    tariffPower: power,
    kwhEstimate: kwh,
    adminFee: 2500,
    totalBill: 125000 + (sumDigits * 1500),
  };
}

